package core;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HashSet;
import java.util.List;
import model.CustomDateObject;
import model.Restaurant;
import model.User;

/**
 * This is a static class used to call the api.
 * Instead of writing long instructions for each call on use,
 * they are gathered in one place.
 */
public class ServerCommunication {
    private static ObjectMapper objectMapper = new ObjectMapper();
    private static HttpClient client = HttpClient.newHttpClient();

    /**
     * Calls the get request for retrieving all saved restaurants.

     * @return all restaurants loaded from server module.
     */
    public static Collection<Restaurant> getAllRestaurants() {
        try {
            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/restaurants"))
                    .GET().build();

            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            Collection<Restaurant> restaurants = objectMapper.readValue(response.body(),
                    new TypeReference<HashSet<Restaurant>>() {
                    });

            return restaurants;
        } catch (Exception e) {
            e.printStackTrace();
            return new HashSet<>();
        }
    }

    /**
     * Calls the post request that saves all restaurants given in paramter to the server.

     * @param restaurants collection of restaurants to be saved.
     */
    public static void saveAllRestaurants(Collection<Restaurant> restaurants) {
        try {
            String jsonContents = objectMapper.writeValueAsString(restaurants);

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/restaurants"))
                    .header("content-type", "application/json").POST(HttpRequest.BodyPublishers.ofString(jsonContents))
                    .build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                System.out.println("All okay!");
            } else {
                System.out.println("Posting failed!");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    /**
     * Calls the get request that retrieves a booking from the server with date and name matching the given parameters.

     * @param date date to compare when searching through the server.
     * @param restaurantName name to compare with when searching through the server.
     * @return All bookings in the server matching the date and name, gathered in one collection.
     */
    public static Collection<CustomDateObject> getBookingsByDateAndRestaurantName(String date, String restaurantName) {
        try {
            // url-string creation generated by ChatGPT
            String url = String.format(
                    "http://localhost:8080/api/bookings?date=%s&restaurantName=%s",
                    URLEncoder.encode(date, StandardCharsets.UTF_8),
                    URLEncoder.encode(restaurantName, StandardCharsets.UTF_8));

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create(url)).GET().build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            Collection<CustomDateObject> returnedBookings = objectMapper.readValue(response.body(),
                    new TypeReference<HashSet<CustomDateObject>>() {
                    });
            return returnedBookings;
        } catch (Exception e) {
            e.printStackTrace();
            return new HashSet<>();
        }
    }

    /**
     * Calls the get request that retrieves all bookings matching the given username.
     * Return type is list for easier sorting.

     * @param user username to use for comparing when searching.
     * @return List of all bookings matching the given username.
     */
    public static List<CustomDateObject> getBookingsByUser(String user) {
        try {
            String url = String.format(
                    "http://localhost:8080/api/bookings?user=%s",
                    URLEncoder.encode(user, StandardCharsets.UTF_8));

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create(url)).GET().build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            List<CustomDateObject> returnedBookings = objectMapper.readValue(response.body(),
                    new TypeReference<List<CustomDateObject>>() {
                    });
            return returnedBookings;
        } catch (Exception e) {
            e.printStackTrace();
            return new ArrayList<>();
        }
    }

    /**
     * Calls the get request for retrieving the booking with and id matching the given id.

     * @param id Id to search for.
     * @return Date object representing booking with matching id.
     */
    public static CustomDateObject getBookingById(String id) {
        try {
            String url = String.format(
                    "http://localhost:8080/api/bookings?id=%s",
                    URLEncoder.encode(id, StandardCharsets.UTF_8));

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create(url)).GET().build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            CustomDateObject returnedBooking = objectMapper.readValue(response.body(),
                    new TypeReference<CustomDateObject>() {
                    });
            return returnedBooking;
        } catch (Exception e) {
            e.printStackTrace();
            return new CustomDateObject();
        }
    }

    /**
     * Calls the get request that retrieves all saved bookings.

     * @return Collection containing all saved bookings.
     */
    public static Collection<CustomDateObject> getAllBookings() {
        try {
            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/bookings"))
                    .GET().build();

            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            Collection<CustomDateObject> bookings = objectMapper.readValue(response.body(),
                    new TypeReference<HashSet<CustomDateObject>>() {
                    });

            return bookings;
        } catch (Exception e) {
            e.printStackTrace();
            return new HashSet<>();
        }
    }

    /**
     * Calls post request that saves a booking.

     * @param bookedTime Date object representing booking to save.
     */
    public static void saveBooking(CustomDateObject bookedTime) {
        try {
            String jsonContents = objectMapper.writeValueAsString(bookedTime);

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/bookings/save"))
                    .header("content-type", "application/json").POST(HttpRequest.BodyPublishers.ofString(jsonContents))
                    .build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                System.out.println("All okay!");
            } else {
                System.out.println("Posting failed!");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    /**
     * Calls post request that deletes a booking from the collection.
     * Does this by reading all bookings, removing the one identical to the given, before writing the updated collection.

     * @param bookingToDelete date object representing the booking to delete.
     */
    public static void deleteBooking(CustomDateObject bookingToDelete) {
        try {
            String jsonContents = objectMapper.writeValueAsString(bookingToDelete);

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/bookings/delete"))
                    .header("content-type", "application/json").POST(HttpRequest.BodyPublishers.ofString(jsonContents))
                    .build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                System.out.println("All okay!");
            } else {
                System.out.println("Posting failed!");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    /**
     * Calls the post request that updates the saved id.
     * Two ids are stored in the file.
     * Reads the saved id, adds one, returns and writes the updated id value.

     * @param idType string indicating which saved id to update.
     * @return the updated id.
     */
    public static int updateId(String idType) {
        try {
            String url = "http://localhost:8080/api/ids?idType=" + URLEncoder.encode(idType, StandardCharsets.UTF_8);
            HttpRequest request = HttpRequest.newBuilder().uri(URI.create(url)).GET().build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            return Integer.parseInt(response.body());
        } catch (Exception e) {
            e.printStackTrace();
            return -1;
        }
    }

    /**
     * Calls the get request that loads all the saved users.

     *  @return Collection of all saved users.
     */
    public static Collection<User> getAllUsers() {
        try {
            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/users")).GET()
                    .build();

            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            Collection<User> users = objectMapper.readValue(response.body(), new TypeReference<HashSet<User>>() {
            });

            return users;
        } catch (Exception e) {
            e.printStackTrace();
            return new HashSet<>();
        }
    }

    /**
     * Calls post request that adds a user to the saved collection.
     * Used when creating new user in login page.

     * @param user user to be added to collection.
     * @return exit code that represents success or not.
     */
    public static int saveUser(User user) {
        try {
            String jsonContents = objectMapper.writeValueAsString(user);

            HttpRequest request = HttpRequest.newBuilder().uri(URI.create("http://localhost:8080/api/users"))
                    .header("content-type", "application/json").POST(HttpRequest.BodyPublishers.ofString(jsonContents))
                    .build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 200) {
                System.out.println("All okay!");
            } else {
                System.out.println("Posting failed!");
            }
            return 0;
        } catch (Exception e) {
            e.printStackTrace();
            return 1;
        }
    }
}
